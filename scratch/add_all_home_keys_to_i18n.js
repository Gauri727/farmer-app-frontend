Object.keys(keysByLang).forEach(lang => {
  const dict = keysByLang[lang];
  Object.keys(dict).forEach(k => {
    const val = dict[k].replace(/'/g, "\\'");
    // Check if key already exists under this language in content
    // We insert right after "mr: {" or "en: {" etc.
    const langHeader = `${lang}: {`;
    if (content.includes(langHeader)) {
      // Check if key is already in dictionary
      const regex = new RegExp(`(${lang}:\\s*\\{[\\s\\S]*?\\b${k}\\s*:)`);
      if (!regex.test(content)) {
        content = content.replace(`${lang}: {`, `${lang}: {\n    ${k}: '${val}',`);
      }
    }
  });
});

fs.writeFileSync(file, content, 'utf8');
